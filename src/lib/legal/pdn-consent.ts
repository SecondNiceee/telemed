/**
 * Согласие на обработку персональных данных - текст, под которым пользователь
 * ставит отметку при регистрации.
 *
 * Отдельный документ, а не пункт внутри оферты: для данных о здоровье согласие
 * должно быть конкретным и предметным (ч. 2 ст. 10, ст. 9 152-ФЗ), а «согласен
 * со всеми условиями» этому не отвечает.
 *
 * Модуль без 'server-only': текст нужен и форме регистрации в браузере, и
 * серверу - он сохраняет версию согласия рядом с отметкой пользователя.
 */

