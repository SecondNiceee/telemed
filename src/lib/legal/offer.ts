/**
 * Публичная оферта на использование сервиса «smartcardio».
 *
 * Что это за документ и чего он НЕ покрывает
 * ------------------------------------------
 * Оферта заключается между ПЛАТФОРМОЙ и пользователем и касается только
 * информационно-технических услуг: аккаунт, поиск врача, бронирование слота,
 * приём оплаты, видеосвязь и переписка.
 *
 * Договор на медицинские услуги заключается между пациентом и МЕДИЦИНСКОЙ
 * ОРГАНИЗАЦИЕЙ, врача которой он выбрал. Платформа его стороной не является:
 * она не оказывает медицинскую помощь и не может ею распоряжаться, потому что
 * лицензия (ст. 2, ст. 69 323-ФЗ) есть у клиники, а не у сервиса.
 *
 * Это то же разделение, что в operator.ts для персональных данных, и оно должно
 * совпадать в обоих документах. Если оферта заявит, что медуслуги оказывает
 * платформа, она признает себя исполнителем медицинской помощи без лицензии -
 * это хуже, чем отсутствие оферты.
 *
 * Почему условия описаны именно так, как работает код
 * ---------------------------------------------------
 * Проверено по коду перед написанием:
 *   - оплата идёт через ЮKassa (src/lib/server/yookassa.ts);
 *   - неоплаченную бронь пользователь снимает сам (/api/appointments/:id/release);
 *   - после оплаты кнопки отмены у пациента НЕТ - отменить может только врач
 *     (/api/appointments/:id/cancel принимает лишь doctors-token);
 *   - отмена врачом СРАЗУ запускает полный возврат через ЮKassa
 *     (refundCancelledAppointment в appointment-payments.ts), а если ЮKassa
 *     в этот момент недоступна - возврат догоняет фоновая сверка.
 *
 * Поэтому основной сценарий в тексте - «врач отмечает, что консультация не
 * состоялась, деньги возвращаются автоматически», причина не важна. Обращение
 * на email оставлено запасным путём: если врач не вышел на связь и отметить
 * некому. Удержания за неявку пациента в оферте НЕТ намеренно: код всё равно
 * возвращает всё, а обещание удерживать, которое не исполняется, вредит при
 * споре с медорганизацией. К тому же по ст. 32 ЗоЗПП удержать можно только
 * доказанные расходы - для онлайн-консультации доказывать их дороже её самой.
 *
 * Модуль без 'server-only': короткая подпись нужна форме регистрации в браузере,
 * а полный текст - серверу, который сохраняет его вместе с акцептом.
 */

