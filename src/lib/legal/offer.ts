/**
 * Плоский текст оферты - сохраняется вместе с акцептом пользователя.
 *
 * По той же причине, что и в согласии на ПДн: редакция со временем меняется, а
 * доказывать придётся ту, которую человек принял в день регистрации. Ссылка на
 * «действующую редакцию» этого не доказывает.
 */
export function offerPlainText(): string {
  return offerClauses()
    .map((clause) => {
      const head = clause.title ? `${clause.title}\n` : ''
      const body = [
        clause.text ?? '',
        (clause.items ?? []).map((item) => `- ${item}`).join('\n'),
      ]
        .filter(Boolean)
        .join('\n')
      return `${head}${body}`
    })
    .join('\n\n')
}
