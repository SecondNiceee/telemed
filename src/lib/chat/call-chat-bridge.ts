/**
 * Реестр открытых комнат звонка.
 *
 * Нужен глобальному тосту о новом сообщении (SocketProvider), чтобы понять:
 * не находится ли пользователь прямо сейчас в звонке по этой консультации.
 * Если находится - тост не показываем вообще. Причина: кнопка тоста уводила
 * на страницу чата через полную перезагрузку, а это выбрасывало человека из
 * комнаты посреди разговора. Само сообщение при этом не теряется: чат
 * консультации доступен прямо в звонке (панель справа), а на кнопке чата
 * горит счётчик непрочитанных.
 *
 * Это намеренно НЕ часть zustand-стора: значение читают императивно в
 * обработчике сокет-события, в рендере оно не участвует, и в сторе давало бы
 * лишние перерисовки на каждое монтирование звонка.
 */

/**
 * Счётчик, а не Set: одна и та же консультация может быть смонтирована дважды
 * в момент перехода между версиями страницы (или из-за двойного вызова
 * эффекта в StrictMode). При простом delete cleanup уходящего экземпляра
 * снял бы отметку, которую только что поставил новый.
 */
const openRooms = new Map<number, number>()

/**
 * Отметить, что комната звонка по консультации открыта.
 * Возвращает функцию снятия отметки - вызывать при размонтировании.
 */
export function registerOpenCallRoom(appointmentId: number): () => void {
  openRooms.set(appointmentId, (openRooms.get(appointmentId) ?? 0) + 1)
  let released = false
  return () => {
    // Защита от повторного вызова cleanup: иначе счётчик уехал бы в минус.
    if (released) return
    released = true
    const next = (openRooms.get(appointmentId) ?? 1) - 1
    if (next <= 0) openRooms.delete(appointmentId)
    else openRooms.set(appointmentId, next)
  }
}

/** Открыта ли сейчас комната звонка по этой консультации. */
export function isInCallRoom(appointmentId: number): boolean {
  return (openRooms.get(appointmentId) ?? 0) > 0
}
