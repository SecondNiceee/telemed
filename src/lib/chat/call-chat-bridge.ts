/**
 * Мост между глобальным тостом о новом сообщении и панелью чата внутри звонка.
 *
 * Тост живёт в SocketProvider (общий на всё приложение), а панель чата - в
 * CallRoom. Без этого моста кнопка тоста делала window.location.assign на
 * страницу чата, что для пользователя, находящегося в звонке, означало полную
 * перезагрузку и вылет из комнаты. Теперь CallRoom регистрирует здесь свою
 * функцию открытия панели, а тост проверяет: если для этой консультации
 * открыта комната звонка - открываем панель, иначе переходим по ссылке.
 *
 * Это намеренно НЕ часть zustand-стора: значение императивное, его читают
 * в обработчике события, и в рендере оно не участвует - в сторе оно давало бы
 * лишние перерисовки на каждое монтирование звонка.
 */

type ChatOpener = () => void

const openers = new Map<number, ChatOpener>()

/**
 * Зарегистрировать открывалку панели чата для консультации.
 * Возвращает функцию отписки - её нужно вызвать при размонтировании.
 */
export function registerCallChatOpener(appointmentId: number, open: ChatOpener): () => void {
  openers.set(appointmentId, open)
  return () => {
    // Удаляем только свою запись: при быстром перемонтировании (или двойном
    // вызове эффекта в StrictMode) cleanup старого экземпляра не должен
    // затирать открывалку, которую успел зарегистрировать новый.
    if (openers.get(appointmentId) === open) openers.delete(appointmentId)
  }
}

/** Открывалка панели, если звонок по этой консультации сейчас открыт. */
export function getCallChatOpener(appointmentId: number): ChatOpener | null {
  return openers.get(appointmentId) ?? null
}
