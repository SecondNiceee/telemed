/**
 * Согласие пациента на запись консультации: единый текст и типы.
 *
 * Модуль намеренно без 'server-only': текст нужен и экрану согласия в браузере,
 * и серверу - тот сохраняет в consentText ровно ту формулировку, которую видел
 * пациент. Если бы текст жил только в компоненте, сохранённая копия со временем
 * разошлась бы с показанной, а подтверждать пришлось бы именно показанную.
 */

export type RecordingConsentStatus = 'pending' | 'granted' | 'declined'

/**
 * Текст согласия целиком - то, что пациент видит перед входом в звонок.
 *
 * Требования к формулировке: конкретная цель, состав данных и кто получит
 * доступ. Общего «согласен с обработкой данных» здесь мало.
 *
 * Про срок хранения здесь намеренно НЕТ ни слова. В первой версии стояло
 * «хранится 180 дней, после чего удаляется» - и это было неправдой:
 * автоудаления записей в системе нет, ничего их не удаляет. Обещание в тексте,
 * под которым пациент нажимает «Согласен», превращает согласие в
 * доказательство неисполненного обязательства - хуже, чем не обещать ничего.
 * Вернуть срок в текст можно только вместе с механизмом, который его исполняет.
 *
 * Про доступ - та же логика. Записи смотрит только медицинская организация
 * (единственный экран - lk-org). У пациента экрана нет, поэтому «по запросу»,
 * а не «в личном кабинете»; у врача нет ни экрана, ни права чтения.
 * Формулировка должна совпадать с разделом 4 политики (privacy-policy.ts).
 */
export const RECORDING_CONSENT_TEXT = [
  `Консультация записывается: видео и звук с камеры и микрофона обоих участников.`,
  `Цель записи - подтверждение содержания консультации и разбор спорных случаев.`,
  `Доступ к записи есть только у медицинской организации, которая проводит консультацию.`,
  `Вы можете получить копию записи по запросу в медицинскую организацию.`,
  `Согласие можно отозвать - для этого обратитесь в медицинскую организацию.`,
  `Согласие можно не давать: консультация состоится в полном объёме, просто без записи.`,
].join('\n')

/** Короткая версия для индикатора в комнате и подписей в интерфейсе. */
export const RECORDING_CONSENT_SUMMARY =
  `Видео и звук консультации. Доступ только у медицинской организации.`

/**
 * Разрешена ли запись при таком решении.
 *
 * Единственное место, где статус превращается в «писать / не писать».
 * Запись разрешает только явное 'granted': 'pending' означает, что пациента
 * ещё не спросили, и молчание согласием не считается.
 */
export function isRecordingAllowedByConsent(status: RecordingConsentStatus | null | undefined): boolean {
  return status === 'granted'
}
