import type { NextRequest } from 'next/server'

/**
 * IP-адрес клиента из заголовков запроса.
 *
 * Зачем нужен отдельно от логики роутов
 * -------------------------------------
 * Адрес используется как элемент доказательства акцепта (согласие на обработку
 * ПДн, принятие оферты): бремя доказывания того, что согласие получено, лежит на
 * операторе. Дата, версия и текст уже сохраняются, IP отвечает на вопрос
 * «откуда пришло подтверждение».
 *
 * Почему именно эти заголовки и в таком порядке
 * ---------------------------------------------
 * Приложение работает за nginx, поэтому `request.ip` содержал бы адрес прокси
 * (127.0.0.1), а не пользователя. Реальный адрес nginx проставляет в X-Real-IP,
 * он и приоритетнее: это одно значение, его нельзя спутать с цепочкой.
 *
 * X-Forwarded-For - запасной вариант, и берётся ПЕРВЫЙ адрес: формат заголовка -
 * `клиент, прокси1, прокси2`, каждый следующий прокси дописывает предыдущего в
 * конец. Взять последний означало бы записать адрес своей же инфраструктуры.
 *
 * Ограничение, о котором стоит знать
 * ----------------------------------
 * Оба заголовка подделываются клиентом, если фронт-прокси их не перезаписывает.
 * Поэтому IP - вспомогательный реквизит акцепта, а не основной: доказательством
 * остаются сохранённый текст, версия и дата, а адрес их дополняет. Проверять
 * подлинность заголовков должен nginx, а не приложение.
 *
 * Возвращает null, когда адрес определить не удалось. Пустая строка тут была бы
 * хуже: в БД NULL честно значит «не определён», а '' выглядит как значение.
 */
export function getClientIp(req: NextRequest): string | null {
  const realIp = req.headers.get('x-real-ip')?.trim()
  if (realIp) return realIp

  const forwarded = req.headers.get('x-forwarded-for')
  if (forwarded) {
    const first = forwarded.split(',')[0]?.trim()
    if (first) return first
  }

  return null
}
