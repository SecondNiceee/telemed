import { type MigrateDownArgs, type MigrateUpArgs, sql } from '@payloadcms/db-postgres'

/**
 * IP-адрес акцепта в согласии на обработку ПДн и в принятии оферты.
 *
 * Зачем
 * -----
 * До этой миграции по акцепту сохранялись дата, версия и текст (см.
 * 20260827_000003 и 20260828_000000). Этого достаточно, чтобы показать, НА ЧТО
 * человек согласился, но не откуда пришло подтверждение. Бремя доказывания
 * получения согласия лежит на операторе, и при заявлении «я не давал согласия»
 * адрес - дополнительный реквизит акцепта.
 *
 * Почему две колонки, а не одна
 * -----------------------------
 * Согласие на обработку ПДн и акцепт оферты - разные сделки, они уже разделены
 * на две группы полей. Сейчас оба реквизита пишутся в одном запросе регистрации,
 * но акцепт новой редакции оферты может произойти позже и с другого адреса, не
 * затрагивая согласие. Одна общая колонка это склеила бы.
 *
 * Почему nullable и без DEFAULT
 * -----------------------------
 * Адрес определяется не всегда: за прокси заголовки могут отсутствовать. NULL
 * значит «не определён», и это честнее, чем DEFAULT со строкой-заглушкой в поле,
 * которое предъявляется как доказательство. У пользователей, зарегистрированных
 * до этой миграции, колонки останутся пустыми - задним числом адрес взять
 * неоткуда, и выдумывать его нельзя.
 *
 * Тип varchar, а не inet: значение только хранится и показывается, поиска и
 * сравнения подсетей по нему нет, а Payload для полей `text` генерирует varchar -
 * иной тип разошёлся бы с ожиданиями схемы.
 *
 * Идемпотентна: каждый шаг под IF NOT EXISTS.
 */
export async function up({ db }: MigrateUpArgs): Promise<void> {
  await db.execute(sql`
    ALTER TABLE "users" ADD COLUMN IF NOT EXISTS "pdn_consent_ip" varchar;
  `)

  await db.execute(sql`
    ALTER TABLE "users" ADD COLUMN IF NOT EXISTS "offer_acceptance_ip" varchar;
  `)
}

export async function down({ db }: MigrateDownArgs): Promise<void> {
  await db.execute(sql`ALTER TABLE "users" DROP COLUMN IF EXISTS "offer_acceptance_ip";`)
  await db.execute(sql`ALTER TABLE "users" DROP COLUMN IF EXISTS "pdn_consent_ip";`)
}
